    // ── RC4: round-trip symmetry across assorted key and data lengths ──────

    [Theory]
    [InlineData(5, 0)]
    [InlineData(5, 1)]
    [InlineData(5, 16)]
    [InlineData(5, 257)]
    [InlineData(16, 0)]
    [InlineData(16, 1)]
    [InlineData(16, 16)]
    [InlineData(16, 257)]
    [InlineData(11, 100)]
    public void Rc4_transform_is_its_own_inverse(int keyLength, int dataLength)
    {
        var key = MakeDeterministicBytes(keyLength);
        var plaintext = MakeDeterministicBytes(dataLength);

        var ciphertext = Rc4.Transform(key, plaintext);
        var roundTripped = Rc4.Transform(key, ciphertext);

        Assert.Equal(plaintext, roundTripped);
    }
