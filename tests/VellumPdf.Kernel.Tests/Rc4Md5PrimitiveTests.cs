    // ── MD5: the complete RFC 1321 §A.5 test suite ──────────────────────────

    [Theory]
    [InlineData("", "d41d8cd98f00b204e9800998ecf8427e")]
    [InlineData("a", "0cc175b9c0f1b6a831c399e269772661")]
    [InlineData("abc", "900150983cd24fb0d6963f7d28e17f72")]
    [InlineData("message digest", "f96b697d7cb7938d525a2f31aaf161d0")]
    [InlineData("abcdefghijklmnopqrstuvwxyz", "c3fcd3d76192e4007dfb496cca67e13b")]
    [InlineData(
        "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789",
        "d174ab98d277d9f5a5611c2c9f419d9f")]
    [InlineData(
        "12345678901234567890123456789012345678901234567890123456789012345678901234567890",
        "57edf4a22be3c955ac49da2e2107b67a")]
    public void Md5_matches_RFC1321_test_suite(string input, string expectedHex)
    {
        var digest = Md5.HashData(Encoding.ASCII.GetBytes(input));

        Assert.Equal(expectedHex, Convert.ToHexStringLower(digest));
    }

    // ── MD5: length sweep across the 56-byte padding boundary and the 64-byte block boundary,
    //    checked against .NET's built-in MD5 as an independent oracle and against the
    //    incremental accumulator fed one byte at a time. ──────────────────────────

    [Theory]
    [MemberData(nameof(LengthsCrossingBlockAndPaddingBoundaries))]
    public void Md5_length_sweep_matches_BCL_oracle(int length)
    {
        var data = MakeDeterministicBytes(length);

        var actual = Md5.HashData(data);
        var expected = System.Security.Cryptography.MD5.HashData(data);

        Assert.Equal(expected, actual);
    }

    [Theory]
    [MemberData(nameof(LengthsCrossingBlockAndPaddingBoundaries))]
    public void Md5_incremental_one_byte_at_a_time_matches_single_shot(int length)
    {
        var data = MakeDeterministicBytes(length);

        var singleShot = Md5.HashData(data);

        var incremental = new Md5.Incremental();
        foreach (var b in data)
            incremental.Append([b]);
        var built = incremental.Finish();

        Assert.Equal(singleShot, built);
    }

    [Fact]
    public void Md5_incremental_split_at_arbitrary_offsets_matches_single_shot()
    {
        // PDF's Algorithm 2 feeds MD5 several distinct pieces (padded password, /O, /P,
        // /ID[0], optionally 0xFFFFFFFF) rather than one contiguous buffer — exercise that
        // multi-Append shape directly, split at offsets that don't line up with the 64-byte
        // block size.
        var data = MakeDeterministicBytes(130);
        var singleShot = Md5.HashData(data);

        var incremental = new Md5.Incremental();
        incremental.Append(data.AsSpan(0, 1));
        incremental.Append(data.AsSpan(1, 30));
        incremental.Append(data.AsSpan(31, 63));
        incremental.Append(data.AsSpan(94, 36));
        var built = incremental.Finish();

        Assert.Equal(singleShot, built);
    }

    public static TheoryData<int> LengthsCrossingBlockAndPaddingBoundaries()
    {
        var data = new TheoryData<int>();
        for (var length = 0; length <= 130; length++)
            data.Add(length);
        return data;
    }

    private static byte[] MakeDeterministicBytes(int length)
    {
        var bytes = new byte[length];
        for (var i = 0; i < length; i++)
            bytes[i] = (byte)(i * 37 + 11);
        return bytes;
    }

    // ── RC4: draft-kaukonen-cipher-arcfour-03, Appendix A test vectors ──────
    //
    // Transcribed directly from the draft text (two independent mirrors — the IETF
    // datatracker and the Mozilla archive — agree byte-for-byte on all three vectors).
    // Appendix A lists "Test Vector 1" (credited to CRYPTLIB), "Test Vector 2" (credited to
    // the Department of Commerce), and "Test Vector 3" (credited to SSH ARCFOUR, a 309-byte
    // Finnish-language plaintext in Latin-1). All three are used below, verbatim.
    //
    // The task brief's originally supplied vectors did not match the draft and are NOT used:
    //   - it gave key 01 23 45 67 89 AB CD EF with plaintext 01 23 45 67 89 AB CD EF; the
    //     draft's Test Vector 1 uses the same key but an all-zero 8-byte plaintext.
    //   - it gave key 61 8A 63 D2 FB with plaintext "dcba" (64 62 63 61); the draft's Test
    //     Vector 2 uses the same key but plaintext DC EE 4C F9 2C.
    // Vector 3's plaintext and ciphertext bytes were transcribed from the draft, not computed
    // by running the implementation under test — a KAT generated from the code it verifies
    // proves nothing.

    [Fact]
    public void Rc4_matches_arcfour_draft_test_vector_1()
    {
        byte[] key = [0x01, 0x23, 0x45, 0x67, 0x89, 0xAB, 0xCD, 0xEF];
        byte[] plaintext = [0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00];
        byte[] expectedCiphertext = [0x74, 0x94, 0xC2, 0xE7, 0x10, 0x4B, 0x08, 0x79];

        var actual = Rc4.Transform(key, plaintext);

        Assert.Equal(expectedCiphertext, actual);
    }

    [Fact]
    public void Rc4_matches_arcfour_draft_test_vector_2_pdf_40_bit_key_length()
    {
        // Also PDF's 40-bit RC4 case (ISO 32000-1 §7.6.2): a 5-byte key.
        byte[] key = [0x61, 0x8A, 0x63, 0xD2, 0xFB];
        byte[] plaintext = [0xDC, 0xEE, 0x4C, 0xF9, 0x2C];
        byte[] expectedCiphertext = [0xF1, 0x38, 0x29, 0xC9, 0xDE];

        var actual = Rc4.Transform(key, plaintext);

        Assert.Equal(expectedCiphertext, actual);
    }

