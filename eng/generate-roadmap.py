# Generates the roadmap block that README.md and the eight src/*/README.md carry (#369).
#
# The block used to be hand-copied into nine files and drifted twice. The source of truth is the
# live GitHub milestone, but CI must not depend on the GitHub API or on unrelated milestone edits,
# so the generator renders from a committed snapshot, eng/roadmap/milestones.json:
#
#   (no flag)  regenerate the nine files from the snapshot.
#   --check    offline; fails if any of the nine files differs from what the snapshot renders.
#              This is the CI gate (docs-roadmap.yml).
#   --refresh  maintainer action; rewrites title, description and released state of every snapshot
#              entry, and latestRelease, from the live milestones via `gh api`, then regenerates the
#              nine files. It still exits 1 when an open live milestone is missing from the snapshot
#              (or a snapshot entry is gone from GitHub): the files are regenerated from what the
#              snapshot has, and the new milestone needs a track and a position added by hand.
#   --drift    read-only; exits 1 if the snapshot differs from the live milestones. Run weekly by
#              docs-roadmap.yml, never on a pull request.
#
# Which milestones appear, their order and their track are curated in the snapshot, because
# GitHub carries none of the three. A live open milestone that is not in the snapshot is reported
# by --refresh and --drift, never guessed at. Row text is the milestone description verbatim, so to
# change a row, edit the milestone and run --refresh. Open-issue counts are omitted: they change
# on every issue move and would keep the files dirty.

import json
import re
import subprocess
import sys

REPO = "Tim81/VellumPDF"
SNAPSHOT = "eng/roadmap/milestones.json"
BEGIN = "<!-- roadmap:begin (generated by eng/generate-roadmap.py; do not edit) -->"
END = "<!-- roadmap:end -->"
FILES = ["README.md"] + [
    f"src/{d}/README.md"
    for d in ("VellumPdf.Barcodes", "VellumPdf.Cli", "VellumPdf.Conformance", "VellumPdf.Fonts.Standard14",
              "VellumPdf.Kernel", "VellumPdf.Layout", "VellumPdf.Reader", "VellumPdf.Signing")
]
# The package READMEs are shown on nuget.org, which renders a repository-relative link with an
# empty href, so they link to the docs by absolute URL. The root README is read in the repository.
DOCS_URL = "https://github.com/Tim81/VellumPDF/blob/main/docs/"
TRACKS = ("kernel", "layout", "editing")


def load():
    with open(SNAPSHOT, encoding="utf-8") as f:
        return json.load(f)


def label(title):
    # "v2.4 — Name" -> "2.4 — Name"; "Layout A — Name" is unchanged.
    return re.sub(r"^v(?=\d)", "", title)


def row(m):
    text = " ".join(m["description"].split()).replace("|", "\\|")
    suffix = " *(released)*" if m.get("released") else ""
    return f"| **{label(m['title'])}**{suffix} | {text} |"


def table(ms):
    return ["| Milestone | Scope |", "| --- | --- |"] + [row(m) for m in ms]


def render(snap, docs_prefix):
    by = {t: [m for m in snap["milestones"] if m["track"] == t] for t in TRACKS}
    out = [
        BEGIN,
        "",
        "Planned direction, tracked as [GitHub milestones](https://github.com/Tim81/VellumPDF/milestones).",
        f"These are scopes, not commitments — the milestones carry no due dates. {snap['latestRelease']} is the latest",
        "published release.",
        "",
        f"Scope past {snap['parallelFrom']} runs as **two parallel tracks**, because auditing the layout engine turned up more",
        "work than the PDF 2.0 conformance gap did. Both ship from the same version numbers.",
        "",
        "**Kernel and conformance**",
        "",
        *table(by["kernel"]),
        "",
        "**Layout**",
        "",
        *table(by["layout"]),
        "",
        "**Editing existing documents.** The only breaking milestone is 3.0.",
        "",
        *table(by["editing"]),
        "",
        "What this library implements of ISO 32000-2 today is inventoried, reference by reference, in",
        f"[PDF 2.0 conformance]({docs_prefix}pdf20-conformance.md). It emits a `%PDF-2.0` header, which is not the",
        f"same as conformance, and the table says which is which. The [Reader guide]({docs_prefix}reader-guide.md)",
        f"and [Layout guide]({docs_prefix}layout-guide.md) each carry a capability table doing the same job for",
        "their own package, checked against the code and test suite rather than against this roadmap.",
        "",
        "`VellumPdf.Reader` is marked Preview in the table above; expect its public surface to settle",
        "as these milestones land. `VellumPdf.Conformance` graduated to Stable in 2.0.",
        END,
    ]
    return "\n".join(out)


def validate(snap):
    errs = []
    if not re.fullmatch(r"\d+\.\d+\.\d+", snap.get("latestRelease", "")):
        errs.append("latestRelease is not a MAJOR.MINOR.PATCH version; run --refresh")
    seen = set()
    for m in snap["milestones"]:
        n = m.get("number")
        if n in seen:
            errs.append(f"milestone {n} listed twice")
        seen.add(n)
        if m.get("track") not in TRACKS:
            errs.append(f"milestone {n}: track must be one of {TRACKS}")
        if not m.get("title") or not m.get("description"):
            errs.append(f"milestone {n}: the snapshot has no title or description for it. If the live "
                        "milestone has both, run --refresh; if its description is empty, write one on "
                        "GitHub first, since the table renders descriptions verbatim")
    return errs


def apply(text, block):
    # Exactly one pair: a duplicated block would otherwise be half-replaced and pass --check once
    # regenerated, hiding the stray copy.
    if text.count(BEGIN) != 1 or text.count(END) != 1:
        return None
    i, j = text.find(BEGIN), text.find(END)
    if j < i:
        return None
    return text[:i] + block + text[j + len(END):]


def read(path):
    with open(path, encoding="utf-8", newline="") as f:
        return f.read()


def targets(snap):
    for p in FILES:
        yield p, render(snap, "docs/" if p == "README.md" else DOCS_URL)


def gh(path):
    r = subprocess.run(["gh", "api", path], capture_output=True, text=True, encoding="utf-8")
    if r.returncode:
        raise SystemExit(f"gh api {path} failed: {r.stderr.strip()}")
    return json.loads(r.stdout)


def live():
    ms = gh(f"repos/{REPO}/milestones?state=all&per_page=100")
    if len(ms) >= 100:
        raise SystemExit("100 or more milestones: add pagination to live() before trusting this")
    return {m["number"]: m for m in ms}, gh(f"repos/{REPO}/releases/latest")["tag_name"].lstrip("v")


def refreshed(snap):
    lm, latest = live()
    new = json.loads(json.dumps(snap))
    problems = []
    for m in new["milestones"]:
        s = lm.get(m["number"])
        if s is None:
            problems.append(f"milestone {m['number']} is in the snapshot but not on GitHub")
            continue
        m["title"], m["description"] = s["title"], (s["description"] or "").strip()
        m["released"] = s["state"] == "closed"
    new["latestRelease"] = latest
    known = {m["number"] for m in new["milestones"]}
    for n, s in lm.items():
        # Patch milestones, Backlog and old closed minors are deliberately not shown, so only an
        # open milestone can be a missing row.
        if n not in known and s["state"] == "open" and s["title"] != "Backlog":
            problems.append(f"open milestone {n} '{s['title']}' is not in the snapshot; add it with a track")
    return new, problems


def save(snap):
    with open(SNAPSHOT, "w", encoding="utf-8", newline="\n") as f:
        json.dump(snap, f, indent=2, ensure_ascii=False)
        f.write("\n")


def main():
    args = sys.argv[1:]
    snap = load()
    if "--drift" in args:
        new, problems = refreshed(snap)
        if new != snap:
            problems.append("snapshot differs from the live milestones; run --refresh and commit")
        for p in problems:
            print(p, file=sys.stderr)
        return 1 if problems else 0
    refresh_problems = []
    if "--refresh" in args:
        snap, refresh_problems = refreshed(snap)
        save(snap)
        for p in refresh_problems:
            print(p, file=sys.stderr)
    errs = validate(snap)
    if errs:
        for e in errs:
            print(e, file=sys.stderr)
        return 1
    stale = []
    for path, block in targets(snap):
        old = read(path)
        new = apply(old, block)
        if new is None:
            print(f"{path}: expected exactly one roadmap:begin and one roadmap:end marker, in that order", file=sys.stderr)
            return 1
        if new != old:
            if "--check" in args:
                stale.append(path)
            else:
                with open(path, "w", encoding="utf-8", newline="") as f:
                    f.write(new)
    if stale:
        print("roadmap block is out of date in: " + ", ".join(stale) + f"; run python {sys.argv[0]}", file=sys.stderr)
        return 1
    return 1 if refresh_problems else 0


if __name__ == "__main__":
    sys.exit(main())
